 const base=inject('baseUrl');const r=await fetch(`${base}/register`,{method:'POST',redirect:'manual',body:new URLSearchParams({username:`spec_mile${Date.now().toString(36)}`,password:'abc123456'})});const cookie=r.headers.get('set-cookie')!.split(';')[0];
 const page=async(path:string)=>new JSDOM(await(await fetch(`${base}${path}`,{headers:{cookie}})).text()).window.document;
 const world=await page('/world');const nest=world.querySelector('#dest-nest')!;
 expect(nest.querySelector(':scope > .nest-warn')).toBeNull();expect(nest.querySelector('details .exploration-stakes')!.textContent).toContain('losing everything carried');
 await fetch(`${base}/world/depart`,{method:'POST',redirect:'manual',headers:{cookie},body:new URLSearchParams({destination:'supermarket'})});
 const activity=await page('/activity');expect(activity.querySelector('.log-card')!.textContent).toContain('Clue card');expect(activity.querySelector('.log-card a')!.getAttribute('href')).toBe('/collection');
 const again=await page('/activity');expect(again.querySelectorAll('.log-card').length).toBe(activity.querySelectorAll('.log-card').length);
