import {mkdtempSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {expect,it,inject} from 'vitest';
import {JSDOM} from 'jsdom';
import {openDb} from '../src/db.ts';
import {createShelter,loadShelter,recentLog,log,depart} from '../src/shelter.ts';
import {settleCollections} from '../src/collections.ts';
import {discoverEnemy,settleEnemyCardLog} from '../src/bestiary.ts';
import {activityPage} from '../src/views.ts';
const now=1800000000000;
it('records clue and enemy cards once, preserves their discovery times, and labels recruitment without merging it into combat',async()=>{
 const db=openDb(mkdtempSync(join(tmpdir(),'holdout-milestones-')));const user=Number(db.prepare("INSERT INTO users(username,password_hash,created_at) VALUES('milestones','x',?)").run(now).lastInsertRowid);createShelter(db,user,'milestones',now);const s=loadShelter(db,user,now);
 db.prepare("INSERT INTO discoveries(shelter_id,fragment_id,found_at) VALUES(?,'cart-dogs',?)").run(s.id,now);
 settleCollections(db,s.id,['cart-dogs'],now);settleCollections(db,s.id,['cart-dogs'],now+1);
 expect(recentLog(db,s.id).filter(e=>e.kind==='card')).toHaveLength(1);
 db.prepare("INSERT INTO discoveries(shelter_id,fragment_id,found_at) VALUES(?,'our-loop',?)").run(s.id,now+2);
 settleCollections(db,s.id,['cart-dogs','our-loop'],now+2);expect(recentLog(db,s.id).filter(e=>e.kind==='card')).toHaveLength(1);
 expect(depart(db,user,'supermarket',now+3).ok).toBe(true);
 const journey=(db.prepare('SELECT id FROM journeys ORDER BY id DESC').get() as {id:number}).id;
 discoverEnemy(db,s.id,'rat',now+3,journey);discoverEnemy(db,s.id,'rat',now+4,journey);settleEnemyCardLog(db,s.id);
 expect(recentLog(db,s.id).filter(e=>e.kind==='enemy-card')).toHaveLength(1);
 db.prepare("INSERT INTO enemy_discoveries(shelter_id,enemy_id,first_seen,journey_id) VALUES(?,'mudback',?,?)").run(s.id,now+5,journey);
 settleEnemyCardLog(db,s.id);settleEnemyCardLog(db,s.id);expect(recentLog(db,s.id).filter(e=>e.kind==='enemy-card')).toHaveLength(2);
 log(db,s.id,now+6,'recruit','Toby moved in.');
 const doc=new JSDOM(String(await activityPage(s,recentLog(db,s.id)))).window.document;
 expect(doc.querySelector('.log-recruit')!.textContent).toContain('NPC recruited');expect(doc.querySelector('.log-recruit a')!.getAttribute('href')).toBe('/#survivor');
 expect(doc.querySelector('.log-card a')!.getAttribute('href')).toBe('/collection');expect(doc.querySelector('.log-enemy-card a')!.getAttribute('href')).toBe('/collection/enemies');
 expect(recentLog(db,s.id).find(e=>e.kind==='card')!.at).toBe(now);db.close();
});
